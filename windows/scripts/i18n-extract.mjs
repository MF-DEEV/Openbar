// Repeatable one-way Swift -> committed JSON; never modifies macOS sources.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const languages = [
  "en-US",
  "pt-BR",
  "tr",
  "ru",
  "es",
  "sk",
  "de",
  "fr",
  "it",
  "ja",
  "ko",
  "uk",
  "zh-Hans",
  "zh-TW",
  "zh-HK",
];
export function flatten(value, prefix = "", out = {}) {
  for (const [key, entry] of Object.entries(value)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof entry === "string") out[path] = entry;
    else flatten(entry, path, out);
  }
  return out;
}
export function writeKeys() {
  const keys = [
    ...new Set([
      ...Object.keys(flatten(JSON.parse(readFileSync("src/i18n/generated/en-US.json", "utf8")))),
      ...Object.keys(JSON.parse(readFileSync("src/i18n/overrides/en-US.json", "utf8"))),
    ]),
  ].sort();
  writeFileSync(
    "src/i18n/keys.d.ts",
    "// Generated by scripts/i18n-extract.mjs. Do not edit.\nexport type CatalogKey =\n" +
      keys.map((k) => `  | ${JSON.stringify(k)}`).join("\n") +
      ";\n",
  );
  const native = {};
  for (const language of languages) {
    const values = flatten(JSON.parse(readFileSync(`src/i18n/generated/${language}.json`, "utf8")));
    native[language] = {
      settings: values["s.menuSettings"],
      quit: values["s.menuQuit"],
      saveScreenshot: values["screenshot.saveAsButton"],
      screenshot: values["screenshot.editorTitle"],
    };
  }
  writeFileSync("src/i18n/native.json", JSON.stringify(native, null, 2) + "\n");
}
if (process.argv.includes("--keys-only")) writeKeys();
else if (process.argv[1]?.endsWith("i18n-extract.mjs")) {
  const python =
    process.env.I18N_PYTHON ??
    (existsSync("build/i18n-python/python.exe")
      ? resolve("build/i18n-python/python.exe")
      : process.platform === "win32"
        ? "python"
        : "python3");
  const out = resolve("build/i18n-extracted");
  const result = spawnSync(
    python,
    ["-I", "tools/i18n-extract/extract_swift_strings.py", "../Sources/Vorssaint/Core", "--out", out],
    { encoding: "utf8", windowsHide: true },
  );
  if (result.error || result.status !== 0) throw result.error ?? new Error(result.stderr);
  const report = JSON.parse(result.stdout.slice(0, result.stdout.indexOf("\nproblems:")));
  const unexpected = result.stdout
    .split(/\r?\n/)
    .filter((l) => l.startsWith("  -") && !l.includes("whatsAppDownloads."));
  if (report.unresolved || unexpected.length) throw new Error("Unresolved Swift tables: " + unexpected.join("\n"));
  mkdirSync("src/i18n/generated", { recursive: true });
  for (const language of languages) {
    const raw = JSON.parse(readFileSync(resolve(out, language + ".json"), "utf8"));
    // The spec's builder-only WhatsApp tables are outside the Windows island.
    const tables = Object.fromEntries(Object.entries(raw).filter(([ns]) => ns !== "whatsAppDownloads"));
    writeFileSync(`src/i18n/generated/${language}.json`, JSON.stringify(tables, null, 2) + "\n");
  }
  writeKeys();
  writeFileSync(
    "src/i18n/extraction-report.json",
    JSON.stringify(
      { ...report, excluded: "whatsAppDownloads builder table (not used by the island)", languages },
      null,
      2,
    ) + "\n",
  );
  console.log(`Extracted ${languages.length} languages; zero unresolved island literals. WhatsApp excluded.`);
}
